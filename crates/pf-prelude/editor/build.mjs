// Bundles src/editor.js and its pinned dependencies into ../js/editor.js (committed), so the
// binary embeds it and serves it as a shared blob. Run `npm ci && npm run build` after changing
// src/editor.js or package.json; the output is deterministic for the same inputs.
import * as esbuild from 'esbuild';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';

const result = await esbuild.build({
  entryPoints: ['src/index.js'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  legalComments: 'eof',
  write: false,
  charset: 'utf8',
});
const header = '/* partifactory formatted view: generated by crates/pf-prelude/editor/build.mjs from src/editor.js. Do not edit. Includes ProseMirror and markdown-it (MIT). */\n';
const out = new URL('../js/editor.js', import.meta.url);
writeFileSync(out, header + result.outputFiles[0].text);
const pkg = JSON.parse(readFileSync(new URL('package.json', import.meta.url)));
// Every bundled package's license, verbatim, next to the sources (NOTICE points here).
// Everything installed except the bundler itself ends up in (or is a dependency of) the bundle.
const bundled = readdirSync(new URL('node_modules/', import.meta.url))
  .flatMap((d) => (d.startsWith('@') ? readdirSync(new URL(`node_modules/${d}/`, import.meta.url)).map((s) => `${d}/${s}`) : [d]))
  .filter((name) => !name.startsWith('.') && !/esbuild/.test(name) && existsSync(new URL(`node_modules/${name}/package.json`, import.meta.url)))
  .sort();
const notices = bundled.map((name) => {
  const dir = new URL(`node_modules/${name}/`, import.meta.url);
  const file = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-MIT.txt', 'license'].map((f) => new URL(f, dir)).find((f) => existsSync(f));
  const version = JSON.parse(readFileSync(new URL('package.json', dir))).version;
  if (!file) throw new Error(`${name} has no LICENSE file`);
  return `${name} ${version}\n\n${readFileSync(file, 'utf8').trim()}\n`;
});
writeFileSync(new URL('THIRD-PARTY-LICENSES.txt', import.meta.url), notices.join('\n' + '-'.repeat(72) + '\n\n'));
console.log(`editor.js: ${(result.outputFiles[0].contents.length / 1024).toFixed(0)} KiB from ${Object.keys(pkg.devDependencies).length} pinned packages`);
