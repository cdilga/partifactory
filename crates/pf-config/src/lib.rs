//! Typed `site.toml` + env config and the secrets loader (the env contract, §5b/§5c).
//!
//! `site.toml` (path `PF_SITE_TOML`, default `/data/site.toml`) is the config; every key is also
//! settable as `PF_<SECTION>_<KEY>`, and env wins. Secrets come from env or `PF_*_FILE` only,
//! never from the file, and live in [`Secret`], which never prints.

pub mod keys;
mod load;
mod secret;
pub mod site;

pub use load::{
    Diag, Env, Loaded, PROTECTIONS, Protection, SECRET_VARS, Secrets, Severity, load,
    load_from_env, site_toml_path, suggest,
};
pub use secret::Secret;
pub use site::SiteConfig;

/// The process environment as an [`Env`] snapshot.
pub fn process_env() -> Env {
    std::env::vars_os()
        .filter_map(|(k, v)| Some((k.into_string().ok()?, v.into_string().ok()?)))
        .collect()
}

/// Emit one `event="config.check"` log line per finding. Never logs a secret value: a
/// [`Diag`] carries variable names only.
pub fn report(diag: &Diag) {
    let fields = diag.fields();
    let get = |name: &str| {
        fields
            .iter()
            .find(|(k, _)| *k == name)
            .map(|(_, v)| v.as_str())
    };
    let (var, key, suggestion) = (get("var"), get("key"), get("suggestion"));
    let detail = diag.to_string();
    match diag.severity() {
        Severity::Error => tracing::error!(
            event = "config.check",
            outcome = diag.outcome(),
            var,
            key,
            suggestion,
            "{detail}"
        ),
        Severity::Warning => tracing::warn!(
            event = "config.check",
            outcome = diag.outcome(),
            var,
            key,
            suggestion,
            "{detail}"
        ),
    }
}

/// `docs/env.md`, generated from the config structs (CI fails if the committed copy differs).
pub fn env_md() -> String {
    let mut s = String::from(
        "# Environment and `site.toml`\n\n\
         <!-- Generated by `partifactory config docs` from crates/pf-config. Do not edit by hand; \
         CI (`ci/env-docs.sh`) fails if this file differs from the generated copy. -->\n\n\
         partifactory reads its config from `site.toml` (path `PF_SITE_TOML`, default \
         `/data/site.toml`). Every key below can also be set as an environment variable, \
         `PF_<SECTION>_<KEY>`, and **the environment wins**. A missing `site.toml` is an empty \
         config. Unknown sections and keys are rejected, with a suggestion.\n\n\
         **Secrets never go in `site.toml`.** Each comes from its variable or from \
         `<VAR>_FILE`, a path to a file holding it (how Docker and compose secrets mount). One \
         trailing newline in the file is trimmed, an empty file counts as missing, and setting \
         both the variable and its `_FILE` is an error.\n\n\
         Run `partifactory config check` to load the config exactly as `serve` would. It prints \
         one JSON line per finding (`event=\"config.check\"`) and exits 2 on any error.\n\n\
         **Keep an offline copy** of `site.toml`, the admin pin and the export age identity in \
         the password manager. Without them, nothing else is recoverable (§5c).\n\n\
         ## Secrets\n\n\
         | Variable | Required | What it is |\n| --- | --- | --- |\n",
    );
    for (var, required, doc) in SECRET_VARS {
        let req = if *required { "yes" } else { "see note" };
        s.push_str(&format!("| `{var}` / `{var}_FILE` | {req} | {doc} |\n"));
    }
    s.push_str(
        "\n## `site.toml` keys\n\n\
         | Key | Env | Type | Default | What it does |\n| --- | --- | --- | --- | --- |\n",
    );
    for k in keys::all() {
        let default = k.default.replace('|', "\\|");
        let default = if default.is_empty() || default == "\"\"" {
            "(unset)".to_string()
        } else {
            format!("`{default}`")
        };
        s.push_str(&format!(
            "| `{}` | `{}` | {} | {} | {} |\n",
            k.path,
            k.env_var(),
            k.ty.name(),
            default,
            k.doc()
        ));
    }
    s.push_str(
        "\n## Protections that need `[unsafe]`\n\n\
         Switching one of these off fails `config check` unless `[unsafe] <name> = \"off\"` is \
         set too, and a set `[unsafe]` key is reported as a warning (§5h).\n\n\
         | Name | Switched off by |\n| --- | --- |\n",
    );
    for p in PROTECTIONS {
        s.push_str(&format!("| `{}` | `{}` |\n", p.name, p.key));
    }
    s
}

