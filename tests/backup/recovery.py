#!/usr/bin/env python3
"""Real CLI recovery drill against an existing disposable e2e harness.

The caller owns shared harness teardown. This driver always terminates its restored
native server, which binds ephemeral loopback ports and needs no host DNS changes.
"""
import argparse
import hashlib
import http.client
import json
import os
from pathlib import Path
import re
import socket
import sqlite3
import subprocess
import tempfile
import time
from urllib.parse import urlsplit


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_dir", type=Path)
    parser.add_argument("--binary", type=Path, default=Path("target/debug/partifactory"))
    parser.add_argument("--https-port", type=int, default=18443)
    args = parser.parse_args()
    run, binary = args.run_dir.resolve(), args.binary.resolve()
    repo = Path(__file__).resolve().parents[2]
    output = repo / "target/e2e-logs" / os.environ.get("PF_E2E_RUN", run.name) / "recovery"
    output.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, PF_SITE_TOML=str(run / "site.toml"), PF_DATA_DIR=str(run / "data"), PF_DEV_IDENTITY=str(run / "identity.toml"), SSL_CERT_FILE=str(run / "certs/ca.pem"))
    for name in ["SESSION_KEY", "CAP_HMAC_KEY", "METRICS_TOKEN", "IDP_CLIENT_SECRET"]:
        env["PF_" + name + "_FILE"] = str(run / "secrets" / name.lower())
        env.pop("PF_" + name, None)
    for name in ["PF_RENDER_PUBLIC_DIR", "PF_LISTEN_RENDER", "PF_RENDER_CDP", "PF_RENDER_CONTROL"]:
        env.pop(name, None)

    def command(arguments, environment=env, expected=0, log=None):
        result = subprocess.run([str(binary)] + arguments, env=environment, text=True, capture_output=True, timeout=90)
        if log:
            (output / log).write_text(result.stdout + result.stderr)
        assert result.returncode == expected, f"{arguments[0]} exited {result.returncode}; expected {expected}; log={log}"
        return result

    compose = ["docker", "compose", "-f", str(repo / "tests/e2e/harness/compose.yaml"), "--profile", "container", "exec", "-T", "partifactory", "/usr/local/bin/partifactory", "dev"]
    dev = [str(binary), "dev", "--socket", str(run / "data/run/dev.sock")] if os.environ.get("PF_HARNESS_MODE", "host") == "host" else compose

    def source_call(op, arguments):
        result = subprocess.run(dev + ["request", op], input=json.dumps(arguments), capture_output=True, text=True, env=env, timeout=45)
        assert result.returncode == 0, f"source dev operation failed: {op}"
        return json.loads(result.stdout)

    # Capture a real cap and browser-compatible fixture session before the CLI export.
    session = source_call("sign-in", {"username": "admin"})
    old = source_call("cap", {"name": "notes"})
    token = (run / "secrets/api_token").read_text().strip()
    seed = subprocess.run(["curl", "--silent", "--show-error", "--fail", "--cacert", str(run / "certs/ca.pem"), "--connect-to", f"parts.pf.test:443:127.0.0.1:{args.https_port}", "--header", "@-", "--header", "Content-Type: application/json", "--data-binary", json.dumps({"name": "notes", "action": "set", "doc_id": "recovery-drill", "data": "recovered", "request_id": "backup-drill-seed"}), "https://parts.pf.test/api/v1/part_data"], input=f"Authorization: Bearer {token}\n", text=True, capture_output=True, timeout=30)
    assert seed.returncode == 0, "real shared-data seed API failed"
    archive = output / f"source-{time.time_ns()}.tar.zst"
    command(["export", "--output", str(archive)], log="export.jsonl")
    command(["export", "--include-secrets"], expected=2, log="secrets-rejected.txt")
    help_text = command(["import", "regrant", "--help"]).stdout
    assert "--plan" in help_text and "--apply" in help_text
    assert '"event":"export.finished"' in (output / "export.jsonl").read_text()

    with tempfile.TemporaryDirectory(prefix="pf-recovery-", dir=run) as temporary:
        temp = Path(temporary)
        unpack = temp / "verified-source"
        unpack.mkdir()
        # This is the archive just generated by our own binary, not an untrusted input.
        subprocess.run(["tar", "-xf", str(archive), "-C", str(unpack)], check=True, capture_output=True)
        manifest = json.loads((unpack / "MANIFEST.json").read_text())
        for name, expected in manifest["entries"].items():
            content = (unpack / name).read_bytes()
            assert hashlib.sha256(content).hexdigest() == expected["sha256"] and len(content) == expected["bytes"], name
        dest = temp / "restored"
        restored_env = dict(env, PF_DATA_DIR=str(dest))
        command(["import", str(archive)], environment=restored_env, log="import.jsonl")
        assert '"event":"import.boot_epoch_bump"' in (output / "import.jsonl").read_text()
        with sqlite3.connect(unpack / "db.sqlite") as before, sqlite3.connect(dest / "partifactory.db") as after:
            counts = {}
            for table in ["parts", "versions", "version_files", "builds", "build_files", "part_notes", "part_tags", "names", "data_docs", "data_snapshots"]:
                original = before.execute(f'SELECT * FROM "{table}"').fetchall()
                actual = after.execute(f'SELECT * FROM "{table}"').fetchall()
                assert sorted(original, key=repr) == sorted(actual, key=repr), table
                counts[table] = len(original)
            assert all(counts[name] > 0 for name in ["parts", "versions", "data_docs", "data_snapshots"]), counts
            assert after.execute("SELECT value FROM kv WHERE key='import_at'").fetchone()
        print("recovery: row-for-row identical", json.dumps(counts, sort_keys=True))
        for name in manifest["entries"]:
            if name.startswith("blobs/"):
                digest = name[6:]
                assert hashlib.sha256((dest / "blobs" / digest[:2] / digest[2:4] / digest).read_bytes()).hexdigest() == digest

        site = temp / "site.toml"
        site.write_text(re.sub(r"(?m)^enabled = true$", "enabled = false", (run / "site.toml").read_text()))
        ports = []
        for _ in range(3):
            with socket.socket() as sock:
                sock.bind(("127.0.0.1", 0))
                ports.append(sock.getsockname()[1])
        restore_env = dict(restored_env, PF_SITE_TOML=str(site), PF_LISTEN_WORKSPACE=f"127.0.0.1:{ports[0]}", PF_LISTEN_CONTENT=f"127.0.0.1:{ports[1]}", PF_LISTEN_OPS=f"127.0.0.1:{ports[2]}")

        def request(port, path, host="parts.pf.test", cookie=False):
            connection = http.client.HTTPConnection("127.0.0.1", port, timeout=5)
            headers = {"Host": host, "Sec-Fetch-Mode": "navigate"}
            if cookie:
                headers["Cookie"] = "__Host-pf_session=" + session["token"]
            try:
                connection.request("GET", path, headers=headers)
                response = connection.getresponse()
                return response.status, dict(response.getheaders()), response.read()
            finally:
                connection.close()

        with (output / "restored-server.jsonl").open("w") as log, (output / "restored-server.stderr").open("w") as errors:
            process = subprocess.Popen([str(binary), "serve"], env=restore_env, stdout=log, stderr=errors)
            try:
                deadline = time.monotonic() + 30
                while True:
                    try:
                        if request(ports[2], "/readyz")[0] == 200:
                            break
                    except OSError:
                        pass
                    assert process.poll() is None and time.monotonic() < deadline, "restored binary failed readiness"
                    time.sleep(.1)
                path = urlsplit(old["url"])
                assert request(ports[1], path.path, path.hostname)[0] in [302, 401]
                # Full exports preserve browser sessions (only part_secrets are
                # omitted without --include-secrets). Prove that recovery property,
                # then exercise a fresh real dev sign-in for the fresh grant gate.
                assert request(ports[0], "/api/session", cookie=True)[0] == 200, "full export lost its retained session"
                signed_in = subprocess.run([str(binary), "dev", "--socket", str(dest / "run/dev.sock"), "request", "sign-in"],
                                           input=json.dumps({"username": "admin"}), capture_output=True,
                                           text=True, env=restore_env, timeout=30)
                assert signed_in.returncode == 0, "restored server fresh sign-in failed"
                session = json.loads(signed_in.stdout)
                status, headers, _ = request(ports[0], "/grant?part=notes", cookie=True)
                assert status == 302 and "/c/" in headers.get("location", ""), "fresh grant failed"
                fresh = urlsplit(headers["location"])
                assert request(ports[1], fresh.path, fresh.hostname)[0] == 200, "fresh cap failed"
                assert request(ports[0], "/admin/health", cookie=True)[0] == 200
            finally:
                process.terminate()
                try:
                    process.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait(timeout=5)
        assert '"outcome":"stale_boot"' in (output / "restored-server.jsonl").read_text()
        print("recovery: pre-export cap rejected; fresh /grant and restored Health returned 200")

        plan = json.loads(command(["import", "regrant", "--plan"], environment=restore_env, log="regrant-plan.json").stdout.splitlines()[-1])
        assert plan["grants"], "fixture should propose matching grants"
        plan_file = temp / "plan.json"
        plan_file.write_text(json.dumps(plan))
        # This isolated fixture models grants awaiting explicit review after import. The
        # source harness and its data are unaffected by these local fixture changes.
        with sqlite3.connect(dest / "partifactory.db") as db:
            for grant in plan["grants"]:
                db.execute("DELETE FROM grants WHERE target_kind='part' AND target_id=? AND subject=?", (grant["part_id"], grant["subject"]))
        first = command(["import", "regrant", "--apply", str(plan_file)], environment=restore_env, log="regrant-apply.jsonl")
        second = command(["import", "regrant", "--apply", str(plan_file)], environment=restore_env, log="regrant-repeat.jsonl")
        assert json.loads(first.stdout.splitlines()[-1])["applied"] > 0
        assert json.loads(second.stdout.splitlines()[-1])["applied"] == 0
        no_pin = temp / "no-pin.toml"
        no_pin.write_text(re.sub(r'(?m)^subject = "[^"\n]*"$', 'subject = ""', site.read_text()))
        with sqlite3.connect(dest / "partifactory.db") as db:
            db.execute("DELETE FROM kv WHERE key='admin.subject'")
        result = subprocess.run([str(binary), "import", "regrant", "--apply", str(plan_file)], env=dict(restore_env, PF_SITE_TOML=str(no_pin)), capture_output=True, text=True, timeout=30)
        assert result.returncode != 0 and "pinned administrator" in result.stderr.lower(), "no-pin apply must refuse"
        corrupt = temp / "corrupt.tar.zst"
        data = bytearray(archive.read_bytes())
        data[len(data)//2] ^= 1
        corrupt.write_bytes(data)
        bad_dest = temp / "corrupt-destination"
        command(["import", str(corrupt)], environment=dict(env, PF_DATA_DIR=str(bad_dest)), expected=3, log="corrupt-rejected.txt")
        assert not bad_dest.exists()
        print("recovery: explicit regrant applied, repeat no-op; no-pin and corrupt import refused before mutation")
    print("recovery: PASS; artifacts", output)


if __name__ == "__main__":
    main()
